// Fraction 0..1 -> a fixed-width block meter, e.g. "███████░░░░░░░ 47%"
export function blockMeter(fraction: number, width = 20): string {
  const clamped = Math.max(0, Math.min(1, fraction));
  const filled = Math.round(clamped * width);
  const pct = Math.round(clamped * 100);
  return "█".repeat(filled) + "░".repeat(width - filled) + ` ${pct}%`;
}

// A double-line frame top/bottom row with an optional title cut into the
// top border, e.g. topRule(60, "transmissions") ->
// "╔═[ transmissions ]═══════════════════════════════════╗"
export function topRule(width: number, title?: string): string {
  if (!title) return "╔" + "═".repeat(Math.max(0, width - 2)) + "╗";
  const label = `═[ ${title} ]═`;
  const remaining = Math.max(0, width - 2 - label.length);
  return "╔" + label + "═".repeat(remaining) + "╗";
}

export function bottomRule(width: number): string {
  return "╚" + "═".repeat(Math.max(0, width - 2)) + "╝";
}
